// Writes src/chain/abis.ts from the Foundry build (run `forge build` in ../contracts first), so the
// agents always use the ABIs of the contracts in this repository.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../../contracts/out/", import.meta.url));
const names = ["CreatorRegistry", "LicenseRegistry", "ReceiptAnchor", "HspSettlement"];
let ts = "// Generated by scripts/abi.ts from contracts/out. Do not edit.\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(`${out}${n}.sol/${n}.json`, "utf8"));
  ts += `\nexport const ${n[0]!.toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(fileURLToPath(new URL("../src/chain/abis.ts", import.meta.url)), ts);
console.log(`wrote ABIs for ${names.join(", ")}`);
